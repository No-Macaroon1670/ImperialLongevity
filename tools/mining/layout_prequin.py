def rec(t, n, wk, a, x, d, extras, hatch):
    e = dict(extras)
    parts = ["n: '%s'" % n, "t: '%s'" % t, "d: '%s'" % d]
    parts.append("a: 'BC%d'" % a)
    if e.get('z_only'):
        parts.append("z: 'BC%d'" % x)
    else:
        z = e.get('z')
        if z: parts.append("z: 'BC%d'" % z)
        xx = e.get('x', x)
        xm = e.get('x_month')
        parts.append("x: 'BC%d%s'" % (xx, '-' + xm if xm else ''))
    if 'c' in e: parts.append("c: %d" % e['c'])
    if e.get('f'): parts.append("f: 1")
    if e.get('l'): parts.append("l: 1")
    F = ('Y' if hatch else '') + e.get('Fx', '') + e.get('F', '')
    if F: parts.append("F: '%s'" % F)
    parts.append("tc: '王'")
    parts.append("wk: '%s'" % wk)
    if e.get('no'): parts.append("no: '%s'" % e['no'].replace("'", "\\'"))
    return '  { %s },' % ', '.join(parts)


