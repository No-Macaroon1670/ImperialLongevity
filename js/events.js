//
// 帝王与政权回答「谁在何时统治」，事件回答「那两千年里发生了什么」。
// 教育类时间轴的主体内容正是这一层，本库此前只有帝王与改朝换代（TRANSITIONS），
// 补上它才算一条完整的时间轴。
//
// 选录标准（宁少勿滥，一百余条而非上千条）：
//   1. **有年份**。系年不定的（如老子生卒）不收；跨年的战争取起年，另记 `y2`。
//   2. **有词条**。每条都能落到中文维基的一个具体条目上——`w` 逐条实测过
//      （REST summary 返回 200 且非消歧义页），否则不收。名字两家不一致时
//      另记 `b`（百度正名），理由见 knowledge.js 的踩坑记录。
//   3. **不与图上已有的东西重复**。这是用户实测指出的问题：太平天国既是政权
//      （已有长带）又被收成事件，同一件事在图上说了两遍。故两条禁令：
//      政权的建立／灭亡不入事件层（长带的起讫已经在说），改朝换代不入事件层
//      （承继细丝的刻痕已能点开）。渲染端另有一道运行时护栏：事件的维基条目
//      若与某条 TRANSITIONS 相同，直接跳过不画。
//   4. **文学名篇要收**。判据放宽过第二次:此前以「纯文学不收」排除了《桃花源记》
//      《兰亭集序》这类——它们现代仍被广泛诵读,又有明确年份,正是时间轴该有的锚点。
//      仍然不收的是无从系年的作品与文人轶事。
//   5. **年份是硬门槛,也是这张图的体裁限制**。《过秦论》《春秋繁露》《日知录》
