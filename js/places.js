/**
 * 这个地名是哪座城的地方线？没有线返回 null。
 *
 * 与 `hitsOf` 是两件事，别混：`hitsOf` 回答「这**一条事件**算不算本地」，
 * 要看角色（收藏族一律不计）、要看坐标半径；这里回答的是「这**个名字**指的是
 * 哪座城」，只认名字。故藏馆名（故宫博物院、陕西历史博物馆……）在这里照样**认**——
 * 那座馆确实在北京城里，这一句是真的。
 *
 * 但**认得**不等于**该给链**（2026-09-07 复核员案，改在调用侧）：〈清明上河图〉的
 * 「现藏地 故宫博物院 →」若链去北京线，读者进的是一张找不到这幅画的页——北京线那
 * 132 条正是 hitsOf 算的，收藏族一条不收。故关系栏的地名胶囊先看角色（knowledge.js
 * 里按 links-index 盖的 `it.hold` 挡掉收藏族），再来问本函数。本函数自己**不管角色**，
 * 也不该管：它只是一张名字表，两个下游（舆图圈沿药丸认的是「这一簇在哪座城」，
 * 关系栏认的是「这条边指的哪座城」）问的问题不一样，滤法各自在各自那头。
 */
export const placeOfLoc = (name) => (name ? LOC2KEY.get(String(name).trim()) || null : null);

/**
 * 这个地方的圆心表：`[[lon, lat, km], …]`。一城一圆的老写法（center＋radiusKm）与
 * 区域线的多圆写法（centers）在这里归一，下游只认这一张表。
 *
 * 区域线（库主 2026-09-09 起：江南「太湖两岸，江海之间」、成都平原）不是一座城，
 * 是十来个县市的并集——一个大圆罩不住（江南东西三百公里，罩到了就把南京杭州也吞进来），
 * 故改成若干小圆的并集：任一落点进任一圆即算。已有六城一字不改，仍走 center＋radiusKm。
 */
export const centersOf = (place) => (Array.isArray(place.centers) && place.centers.length
  ? place.centers
  : [[place.center[0], place.center[1], place.radiusKm]]);

/** 页面上说口径用的一句：单圆「城中心 N 公里内」，多圆「N 个圆心各 M 公里内」。 */
export const radiusText = (place) => {
  const cs = centersOf(place);
  if (cs.length === 1) return `城中心 ${cs[0][2]} 公里内`;
  const kms = [...new Set(cs.map((c) => c[2]))].sort((a, b) => a - b);
  return `${cs.length} 个圆心各 ${kms.length === 1 ? kms[0] : kms[0] + '–' + kms[kms.length - 1]} 公里内`;
};

// `地名:角色` 拆件。切在**最后一个冒号**上，与 build_geo_events.py 的
// TOKEN = ^(.+?):([^:]+)$ 同法：角色里不会有冒号，地名里将来可能有
const splitP = (s) => {
  const t = String(s);
  const i = t.lastIndexOf(':');
  return i < 0 ? { 名: t, 角: '' }
    : { 名: t.slice(0, i).trim(), 角: t.slice(i + 1).replace(/[*~]/g, '').trim() };
};

// 等距圆柱近似的球面距离。八十公里的尺度上与大圆距离差不到千分之一，
// 而这套判断本来就只是「在不在这座城附近」——没有必要为它引一个 haversine
const RAD = Math.PI / 180;
function distKm([lat1, lon1], [lat2, lon2]) {
  const dLat = (lat2 - lat1) * RAD;
  const dLon = (lon2 - lon1) * RAD * Math.cos(((lat1 + lat2) / 2) * RAD);
  return Math.sqrt(dLat * dLat + dLon * dLon) * 6371;
}

/**
 * 一条事件属不属于这个地方？属于则返回**命中理由**（给交卷核对与页面上的
 * 落点小字用），不属于返回 null。
 *
 * 判据（库主 2026-09-02 裁语，勿改）：
 *   ① `p` 里任一项地名 ∈ family，且角色不在收藏族；或
 *   ② GEO_EVENTS 里该条任一落点在 center 的 radiusKm 内，且角色不在收藏族。
 *   exclude 里的条目名一律剔除，一票否决在最前。
 */
export function hitsOf(ev, place, geoEvents) {
  if (place.exclude && place.exclude.includes(ev.n)) return null;
  const fam = place.family instanceof Set ? place.family : new Set(place.family || []);
  const hits = [];
  for (const item of ev.p || []) {
    const { 名, 角 } = splitP(item);
    if (fam.has(名) && !HOLD_ROLES.has(角)) hits.push({ 名, 角, 由: '族表' });
  }
  const g = geoEvents && geoEvents[ev.n];
  if (g && Array.isArray(g['链'])) {
    // 圆心是 [lon, lat]，geo 的点是 [lat, lon]——就在这里拧一次，别处不再拧。
    // 多圆取最近的那个圆记 km（区域线一处落点可能同时在两个圆里，只记一次）
    const cs = centersOf(place).map(([lon, lat, km]) => [[lat, lon], km]);
    for (const nd of g['链']) {
      if (!nd['点'] || HOLD_ROLES.has(nd['角'])) continue;
      let best = null;
      for (const [c, km] of cs) {
        const d = distKm(c, nd['点']);
        if (d <= km && (best === null || d < best)) best = d;
      }
      if (best !== null) hits.push({ 名: nd['名'], 角: nd['角'], 由: '半径', km: Math.round(best) });
    }
  }
  if (!hits.length) return null;
  // 同一处地方可能既由族表又由半径命中（多数条如此），合成一行免得小字念两遍
  const seen = new Set();
  return hits.filter((x) => {
    const k = `${x.名}:${x.角}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

/**
 * 抽出这个地方的全部成员，按年升序。返回的每条是**事件的浅拷贝加一个 `hits`**：
 * 浅拷贝只为挂住命中理由，字段一个不挑、一个不改——事件层随时在长，
 * 在这里挑字段等于给自己埋一份会过期的副本。
 *
 * 排序不能靠 EVENTS 的原序——那份数组按补录批次堆叠，实测北京段里
 * 1753（豆汁）后面直接跟着 1644（圈地令）。
 */
export function membersOf(place, events, geoEvents) {
  const out = [];
  for (const ev of events) {
    if (ev.y > PLACE_END) continue;          // 轴止于 1912，之后的事不入线
    const hits = hitsOf(ev, place, geoEvents);
    if (hits) out.push({ ...ev, hits });
  }
  return out.sort((a, b) => a.y - b.y || String(a.n).localeCompare(String(b.n), 'zh'));
}
