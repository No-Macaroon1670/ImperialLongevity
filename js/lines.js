// lines.js — 策展故事线：把散落在四千年里的站点串成一条可走的读法。
//
// 与新手导览（tour.js 的 DEFAULT_STOPS）共用同一套引擎与同一套约定
// （打光、落位、清场、一屏预算，逐条见 docs/idea-storylines.md「四之五」）。
// 两者的分工是：**导览教你怎么读这张图，故事线用这张图讲一件事**。
//
// 故此站点字段收窄（同上档「四之五·D」）：
//   · 不用 `set`——随手改筛选与视图会让读者迷路；确需换读法的，写成显式的一站；
//   · 不用 `ctrl` / `legend` / `search` / `links`——那些是指着界面控件讲用法的
//     钩子（`links` 会去照亮卡上的 YouTube 与 B 站按钮）。故事线照亮的只能是
//     **这一站在讲的那个东西**（用户实测：金刚经那站把视频按钮点亮了，莫名其妙）；
//   · `cta`（功能句）对故事线恒空：导览的每一站要教一个方法，故事线的每一站
//     只讲史，方法上一条线里已经教过了。文案因此只有两级：
//     `b` 一句主旨（永远显示）＋ `b2` 其余（详解；宽屏自动摊平成一段）。
//
// 每条线的最后一站收在「回环」上——把开头那个问题重新问一遍，而答案已经变了。

