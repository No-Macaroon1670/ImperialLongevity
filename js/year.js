// year.js — 年份显示原语（零依赖叶子模块，浏览器与 node 两侧同吃）
// -----------------------------------------------------------------------------
// 库内一律用天文纪年存年份：公元前 n 年记作 -(n-1)，故 -220＝前 221、0＝前 1。
// 转成人话时**须加一**（`-y + 1`）——此处漏加即全库公元前晚一年，
// 舆图曾因自带副本脱靶一次（2026-08-31 补，见 app-map.js 的注）。
// 负支同样要 Math.round：入参可能是像素反推的浮点（views-lanes.js:1076 的「时点」），
// 不取整则 -220.4 会渲染成「前221.4」。
// 此前正本在 charts.js，为免 app-map.js / schema.js 这类不画图的页面
// 为五行函数拉进整套图表框架，2026-09-04 迁到本模块，charts.js 原样 re-export。
// -----------------------------------------------------------------------------

/** 天文纪年 → 人话年份串：-220 → 「前221」，1911 → 「1911」。 */
export const fmtYearAxis = (y) => (y <= 0 ? `前${-Math.round(y) + 1}` : String(Math.round(y)));

/**
 * 大事记的年份串：有讫年就显区间，否则只一个年份（2026-09-04 归一，SSOT 卷 D02）。
 * 分隔是**紧排的短横**（U+2013，两侧无空格）——事件类紧排、政权类宽排是库内
 * 既有的排印约定，故这只管事件那一路：`app-map.js` 坞行的 `前 221 – 前 210`
 * 是地图页政权行的宽排版式，**不走本函数**；`app-place.js` 分档抬头的判据是
 * `y2 > y`（能挡「221–221」），与这里的真值判据不同，也不走。
 */
export const fmtSpan = (y, y2) => (y2 ? `${fmtYearAxis(y)}–${fmtYearAxis(y2)}` : fmtYearAxis(y));
